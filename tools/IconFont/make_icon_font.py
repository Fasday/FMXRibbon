"""Builds the icon font that replaces Segoe Fluent Icons where it is not installed (Linux).

Reads segoe-fluent-map.txt (Segoe code point -> Fluent UI System Icons name), takes the named icons out of
FluentSystemIcons-Resizable.ttf (MIT, microsoft/fluentui-system-icons), renames the family to "FMR Fluent Icons" and
writes:
  Assets/Fonts/FmrFluentIcons.ttf      only the mapped icons, at their original code points
  Source/Core/FMR.Ribbon.IconFont.inc  the table Segoe code -> code point in FmrFluentIcons.ttf

Usage: python make_icon_font.py <FluentSystemIcons-Resizable.ttf> <FluentSystemIcons-Resizable.json> <repo root>
       [--source "<url/commit of the font>"] [--check]
Needs fontTools (pip install fonttools). Called by make-icon-font.ps1, which downloads the font.
"""
import json
import os
import re
import sys

FAMILY = 'FMR Fluent Icons'
PS_NAME = 'FMRFluentIcons-Regular'


def read_map(path):
    entries = []
    for n, line in enumerate(open(path, encoding='utf-8-sig'), 1):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        m = re.match(r'^([0-9A-Fa-f]{4,5})\s+([a-z0-9_]+)(?::(filled|regular))?\s*$', line)
        if not m:
            raise SystemExit(f'{path}:{n}: cannot read "{line}"')
        comment = ''
        raw = open(path, encoding='utf-8-sig').read().splitlines()[n - 1]
        if '#' in raw:
            comment = raw.split('#', 1)[1].strip()
        entries.append((int(m.group(1), 16), m.group(2), m.group(3) or 'regular', comment))
    return entries


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    check = '--check' in sys.argv
    source = ''
    if '--source' in sys.argv:
        source = sys.argv[sys.argv.index('--source') + 1]
        args = [a for a in args if a != source]
    ttf, js, root = args[:3]
    names = json.load(open(js, encoding='utf-8'))
    entries = read_map(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'segoe-fluent-map.txt'))
    missing = []
    table = []
    seen = set()
    for code, name, style, comment in entries:
        if code in seen:
            raise SystemExit(f'duplicate code {code:04X}')
        seen.add(code)
        key = f'ic_fluent_{name}_20_{style}'
        if key not in names:
            missing.append(f'{code:04X} {name}:{style}')
            continue
        table.append((code, names[key], name, style, comment))
    if missing:
        print('not in the font:\n  ' + '\n  '.join(missing))
        raise SystemExit(1)
    print(f'{len(table)} icons mapped')
    if check:
        return

    from fontTools.ttLib import TTFont
    from fontTools import subset

    font = TTFont(ttf)
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ['*']
    options.notdef_outline = True
    options.glyph_names = False
    options.hinting = False
    options.desubroutinize = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=sorted({t[1] for t in table}))
    sub.subset(font)
    name_table = font['name']
    for rec in list(name_table.names):
        if rec.nameID in (1, 3, 4, 6, 16, 17, 21, 22):
            name_table.removeNames(nameID=rec.nameID)
    for pid, eid, lid in ((3, 1, 0x409), (1, 0, 0)):
        name_table.setName(FAMILY, 1, pid, eid, lid)
        name_table.setName('Regular', 2, pid, eid, lid)
        name_table.setName(f'{FAMILY} Regular (subset of FluentSystemIcons-Resizable)', 3, pid, eid, lid)
        name_table.setName(FAMILY, 4, pid, eid, lid)
        name_table.setName(PS_NAME, 6, pid, eid, lid)
    out_ttf = os.path.join(root, 'Assets', 'Fonts', 'FmrFluentIcons.ttf')
    os.makedirs(os.path.dirname(out_ttf), exist_ok=True)
    font.save(out_ttf)
    print(f'{out_ttf}: {os.path.getsize(out_ttf)} bytes')

    lines = [
        '// GENERATED by tools\\IconFont\\make-icon-font.ps1 from tools\\IconFont\\segoe-fluent-map.txt. Do not edit.',
        f'// Segoe Fluent Icons / Segoe MDL2 Assets code point -> code point of the same icon in "{FAMILY}"',
        '// (Assets\\Fonts\\FmrFluentIcons.ttf: icons of Fluent UI System Icons, MIT, Copyright (c) 2020 Microsoft',
        f'// Corporation; {source or "microsoft/fluentui-system-icons"}).',
        '',
        f'  FmrIconFontMapCount = {len(table)};',
        f'  FmrIconFontMap: array [0..{len(table) - 1}] of TFmrIconFontMapEntry = (',
    ]
    for i, (code, target, name, style, comment) in enumerate(sorted(table)):
        sep = ',' if i < len(table) - 1 else ');'
        suffix = '' if style == 'regular' else f' ({style})'
        lines.append(f'    (Code: ${code:04X}; Fallback: ${target:04X}){sep} // {name}{suffix}; {comment}')
    out_inc = os.path.join(root, 'Source', 'Core', 'FMR.Ribbon.IconFont.inc')
    with open(out_inc, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{out_inc}: {len(table)} entries')


if __name__ == '__main__':
    main()
